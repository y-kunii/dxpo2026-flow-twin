#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
# shellcheck source=control_token.sh
source "$ROOT/scripts/control_token.sh"

fail() {
  printf 'Spatial application startup failed: %s\n' "$1" >&2
  exit 2
}

usage() {
  cat <<'EOF'
Usage: ./scripts/start_distribution.sh [--view-only | --check-gpu]

  (no option)  Start every bundled service. GPU distributions verify Docker
               GPU passthrough before building the application.
  --view-only  Start the Web application and API without the local VLM worker.
               Bundled scenes and existing analysis records remain available;
               new AI analysis is disabled.
  --check-gpu  Test NVIDIA GPU access from the active Docker daemon and exit.
EOF
}

startup_mode="full"
case "${1:-}" in
  "") ;;
  --view-only) startup_mode="view-only" ;;
  --check-gpu) startup_mode="check-gpu" ;;
  -h|--help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    fail "unknown option: $1"
    ;;
esac
if (($# > 1)); then
  usage >&2
  fail 'only one startup option may be specified'
fi

command -v docker >/dev/null || fail 'Docker is not installed or is not on PATH'
docker compose version >/dev/null 2>&1 || fail 'Docker Compose v2 is not available'
docker info >/dev/null 2>&1 || fail 'Docker daemon is not running or is not accessible'

docker_runtime_summary() {
  local context server_name server_os
  context="$(docker context show 2>/dev/null || printf 'unknown')"
  server_name="$(docker info --format '{{.Name}}' 2>/dev/null || printf 'unknown')"
  server_os="$(docker info --format '{{.OperatingSystem}}' 2>/dev/null || printf 'unknown')"
  printf 'Docker context: %s\nDocker server: %s (%s)\n' "$context" "$server_name" "$server_os"
  if [[ -n "${WSL_DISTRO_NAME:-}" ]]; then
    printf 'WSL distribution: %s\n' "$WSL_DISTRO_NAME"
  fi
}

print_gpu_recovery() {
  cat >&2 <<'EOF'

The host can run nvidia-smi, but the active Docker daemon cannot assign the
GPU to a container. This is host configuration and cannot be installed inside
the application ZIP.

Windows + WSL2 + Docker Desktop:
  1. Update the Windows NVIDIA driver.
  2. In an Administrator PowerShell run: wsl --update; wsl --shutdown
  3. Enable Docker Desktop > Settings > General > Use the WSL 2 based engine.
  4. Enable this Ubuntu distribution under Resources > WSL Integration.
  5. Restart Docker Desktop, reopen Ubuntu, and run this check again.
  Do not add --runtime=nvidia when testing Docker Desktop.

Ubuntu with Docker Engine inside Ubuntu/WSL (not Docker Desktop):
  Install NVIDIA Container Toolkit for that Docker daemon, then run:
    sudo nvidia-ctk runtime configure --runtime=docker
    sudo systemctl restart docker
  Run this check again after restarting Docker.

Official instructions:
  https://docs.docker.com/desktop/features/gpu/
  https://docs.nvidia.com/datacenter/cloud-native/container-toolkit/latest/install-guide.html

To inspect the bundled scene and existing analysis records without GPU access:
  ./scripts/start_distribution.sh --view-only
EOF
}

check_docker_gpu() {
  local output status=0
  printf 'Checking NVIDIA GPU access from the active Docker daemon...\n'
  docker_runtime_summary
  if output="$(
    timeout "${SPATIAL_GPU_CHECK_TIMEOUT_SEC:-180}" \
      docker run --rm --gpus all \
      "${SPATIAL_GPU_CHECK_IMAGE:-ubuntu:24.04}" nvidia-smi 2>&1
  )"; then
    printf '%s\nDocker GPU check passed.\n' "$output"
    return 0
  else
    status=$?
  fi
  printf '%s\n' "$output" >&2
  print_gpu_recovery
  return "$status"
}

check_pytorch_gpu() {
  printf 'Building the pinned local-AI runtime for a PyTorch GPU compute check...\n'
  mkdir -p "$ROOT/models" "$ROOT/var/spatial"
  docker compose build frame-vlm-worker
  printf 'Checking PyTorch architecture compatibility and BF16 CUDA execution...\n'
  docker compose run --rm --no-deps frame-vlm-worker \
    python3 scripts/verify_generation_environment.py \
      --lock generation_pipeline/runtime_environment.lock.json \
      --model-root /opt/models \
      --require-gpu
}

if [[ "$startup_mode" == "check-gpu" ]]; then
  check_docker_gpu || fail 'Docker GPU check failed; follow the recovery steps above'
  if docker compose config --services | grep -qx 'frame-vlm-worker'; then
    check_pytorch_gpu || fail 'PyTorch GPU compute check failed; this application image does not support the detected GPU architecture'
  fi
  exit 0
fi

spatial_ensure_control_token "$ROOT"
export LOCAL_UID="${LOCAL_UID:-$(id -u)}"
export LOCAL_GID="${LOCAL_GID:-$(id -g)}"
export APP_PORT="${APP_PORT:-8080}"
export ROSBRIDGE_PORT="${ROSBRIDGE_PORT:-9090}"

persist_distribution_environment() {
  local environment_file="$ROOT/.env"
  local temporary
  umask 077
  temporary="$(mktemp "$ROOT/.env.tmp.XXXXXX")"
  {
    printf '# Generated by scripts/start_distribution.sh. Keep this file private.\n'
    printf 'SPATIAL_CONTROL_TOKEN=%s\n' "$SPATIAL_CONTROL_TOKEN"
    printf 'LOCAL_UID=%s\n' "$LOCAL_UID"
    printf 'LOCAL_GID=%s\n' "$LOCAL_GID"
    printf 'APP_PORT=%s\n' "$APP_PORT"
    printf 'ROSBRIDGE_PORT=%s\n' "$ROSBRIDGE_PORT"
    if [[ -n "${COMPOSE_PROJECT_NAME:-}" ]]; then
      printf 'COMPOSE_PROJECT_NAME=%s\n' "$COMPOSE_PROJECT_NAME"
    fi
  } >"$temporary"
  chmod 0600 "$temporary"
  mv -f -- "$temporary" "$environment_file"
}

validate_port() {
  local name="$1"
  local value="$2"
  case "$value" in
    ''|*[!0-9]*) fail "$name must be an integer from 1 to 65535" ;;
  esac
  if ((value < 1 || value > 65535)); then
    fail "$name must be an integer from 1 to 65535"
  fi
}

port_is_open() {
  local port="$1"
  timeout 1 bash -c "</dev/tcp/127.0.0.1/${port}" >/dev/null 2>&1
}

websocket_is_available() {
  command -v curl >/dev/null || return 1
  local response
  response="$(
    curl --http1.1 --include --no-buffer --max-time 1 \
      --header 'Connection: Upgrade' \
      --header 'Upgrade: websocket' \
      --header 'Sec-WebSocket-Version: 13' \
      --header 'Sec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ==' \
      "http://127.0.0.1:${ROSBRIDGE_PORT}/" 2>/dev/null || true
  )"
  grep -q '101 Switching Protocols' <<<"$response"
}

validate_port APP_PORT "$APP_PORT"
validate_port ROSBRIDGE_PORT "$ROSBRIDGE_PORT"
persist_distribution_environment

services=(application-api app)
available_services="$(docker compose config --services)"
for optional_service in image-feature-worker frame-vlm-worker; do
  if grep -qx "$optional_service" <<<"$available_services"; then
    if [[ "$startup_mode" == "view-only" && "$optional_service" == "frame-vlm-worker" ]]; then
      continue
    fi
    services+=("$optional_service")
  fi
done

if [[ "$startup_mode" == "full" ]] \
  && grep -qx 'frame-vlm-worker' <<<"$available_services"; then
  check_docker_gpu || fail 'Docker GPU check failed; the application was not built or started'
  check_pytorch_gpu || fail 'PyTorch GPU compute check failed; the application was not started'
fi

if [[ "$startup_mode" == "view-only" ]] \
  && grep -qx 'frame-vlm-worker' <<<"$available_services"; then
  docker compose stop frame-vlm-worker >/dev/null 2>&1 || true
  printf 'View-only mode: local VLM worker is disabled; existing records remain readable.\n'
fi
rosbridge_status='not bundled'
if grep -qx 'rosbridge' <<<"$available_services"; then
  if port_is_open "$ROSBRIDGE_PORT"; then
    if websocket_is_available; then
      rosbridge_status="existing rosbridge WebSocket on port ${ROSBRIDGE_PORT}"
      printf 'Using %s; the bundled rosbridge container will not be started.\n' "$rosbridge_status"
    else
      fail "port ${ROSBRIDGE_PORT} is occupied by a non-WebSocket service"
    fi
  else
    services+=(rosbridge)
    rosbridge_status='bundled rosbridge container'
  fi
fi

if port_is_open "$APP_PORT" \
  && ! docker compose ps --status running --services | grep -qx 'app'; then
  fail "port ${APP_PORT} is already in use; stop that service or run APP_PORT=<free-port> ./scripts/start_distribution.sh"
fi

# A distributed checkout is mounted at /workspace as read-only.  Docker needs
# this nested path to exist before it can attach the dependency named volume.
mkdir -p "$ROOT/web_viewer/app/node_modules" "$ROOT/models"

docker compose up \
  --build \
  --detach \
  --wait \
  --wait-timeout "${SPATIAL_START_TIMEOUT_SEC:-300}" \
  "${services[@]}"
printf 'Spatial application is ready: http://localhost:%s/\n' "$APP_PORT"
if [[ "$startup_mode" == "view-only" ]]; then
  printf 'Mode: view-only (new registered-frame AI analysis is unavailable)\n'
fi
if [[ "$rosbridge_status" != 'not bundled' ]]; then
  printf 'rosbridge: ws://127.0.0.1:%s (%s)\n' "$ROSBRIDGE_PORT" "$rosbridge_status"
fi
